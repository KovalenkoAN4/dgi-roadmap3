# ----------------------------------------------------------------------
# Работа с Google Таблицей
# ----------------------------------------------------------------------
def get_sheet():
    """Возвращает worksheet 'Заметки' или None, если secrets не настроены."""
    try:
        info = st.secrets["gspread"]["service_account_info"]
        sheet_id = st.secrets["sheet"]["sheet_id"]
    except Exception:
        return None
    import gspread
    from google.oauth2.service_account import Credentials
    scopes = ["https://www.googleapis.com/auth/spreadsheets"]
    creds = Credentials.from_service_account_info(info, scopes=scopes)
    gc = gspread.authorize(creds)
    sh = gc.open_by_key(sheet_id)
    try:
        ws = sh.worksheet("Заметки")
    except gspread.WorksheetNotFound:
        ws = sh.add_worksheet("Заметки", rows=200, cols=10)
        ws.update("A1:D1", [["№", "Статус", "Заметки", "Ответственный"]])
    return ws

def load_notes(ws):
    if ws is None:
        return {}
    try:
        rows = ws.get_all_values()
    except Exception:
        return {}
    out = {}
    for r in rows[1:]:
        if r and r[0].strip().isdigit():
            num = int(r[0])
            out[num] = {
                "Статус": r[1] if len(r) > 1 and r[1] in STATUSES else "Не начато",
                "Заметки": r[2] if len(r) > 2 else "",
            }
    return out

def save_note(ws, num, status, note):
    if ws is None:
        return
    try:
        col = ws.col_values(1)
        row = None
        for i, v in enumerate(col):
            if v.strip() == str(num):
                row = i + 1
                break
        if row:
            ws.update(f"B{row}:C{row}", [[status, note]])
        else:
            ws.append_row([str(num), status, note])
    except Exception as e:
        st.error(f"Не удалось сохранить в Google Таблицу: {e}")

